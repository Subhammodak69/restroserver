-- DESTRUCTIVE RESET: this file drops the previous Restro application tables.
-- Run only when intentionally replacing the old database model.
DROP TABLE IF EXISTS audit_log, points_ledger, reviews, payments, bills, delivery_jobs,
  service_requests, order_items, orders, item_options, menu_items, menu_categories,
  categories, table_sessions, restaurant_tables, delivery_zones, customer_addresses,
  otp_challenges, staff, customers, stations, users, addresses, expenses, settings,
  restaurants CASCADE;

CREATE TABLE restaurants (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(160) NOT NULL,
  tagline VARCHAR(200) NOT NULL DEFAULT '',
  phone VARCHAR(32) NOT NULL DEFAULT '',
  email VARCHAR(180) NOT NULL DEFAULT '',
  address JSONB NOT NULL DEFAULT '{}',
  hours JSONB NOT NULL DEFAULT '[]',
  currency CHAR(3) NOT NULL DEFAULT 'INR',
  tax_percent NUMERIC(5,2) NOT NULL DEFAULT 5 CHECK (tax_percent BETWEEN 0 AND 100),
  service_charge_percent NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (service_charge_percent BETWEEN 0 AND 100),
  delivery_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  delivery_fee NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (delivery_fee >= 0),
  min_delivery_order NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (min_delivery_order >= 0),
  is_open BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE delivery_zones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
  postal_code VARCHAR(12) NOT NULL,
  delivery_fee NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (delivery_fee >= 0),
  minimum_order NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (minimum_order >= 0),
  estimated_minutes SMALLINT NOT NULL DEFAULT 45,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (restaurant_id, postal_code)
);

CREATE TABLE stations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
  name VARCHAR(80) NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (restaurant_id, name)
);

CREATE TABLE menu_categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
  name VARCHAR(80) NOT NULL,
  sort_order INTEGER NOT NULL DEFAULT 0,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (restaurant_id, name)
);

CREATE TABLE restaurant_tables (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
  number VARCHAR(16) NOT NULL,
  seats SMALLINT NOT NULL DEFAULT 4 CHECK (seats > 0),
  status VARCHAR(20) NOT NULL DEFAULT 'FREE' CHECK (status IN ('FREE','OCCUPIED','NEEDS_HELP','BILL_REQUESTED','CLEANING')),
  qr_token VARCHAR(96) NOT NULL UNIQUE,
  pos_x SMALLINT NOT NULL DEFAULT 0,
  pos_y SMALLINT NOT NULL DEFAULT 0,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (restaurant_id, number)
);

CREATE TABLE customers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone VARCHAR(24) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL DEFAULT '',
  points_balance INTEGER NOT NULL DEFAULT 0 CHECK (points_balance >= 0),
  is_blocked BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  last_login_at TIMESTAMPTZ
);

CREATE TABLE otp_challenges (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone VARCHAR(24) NOT NULL,
  code_hash TEXT NOT NULL,
  attempts SMALLINT NOT NULL DEFAULT 0,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_otp_phone_created ON otp_challenges(phone, created_at DESC);

CREATE TABLE staff (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
  name VARCHAR(120) NOT NULL,
  phone VARCHAR(24) NOT NULL,
  password_hash TEXT NOT NULL,
  role VARCHAR(20) NOT NULL CHECK (role IN ('SUPERADMIN','MANAGER','WAITER','KITCHEN','DELIVERY')),
  station_id BIGINT REFERENCES stations(id) ON DELETE SET NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (restaurant_id, phone)
);

CREATE TABLE menu_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
  category_id BIGINT NOT NULL REFERENCES menu_categories(id),
  station_id BIGINT REFERENCES stations(id) ON DELETE SET NULL,
  name VARCHAR(120) NOT NULL,
  description VARCHAR(500) NOT NULL DEFAULT '',
  image_url VARCHAR(500) NOT NULL DEFAULT '',
  price NUMERIC(10,2) NOT NULL CHECK (price >= 0),
  is_vegetarian BOOLEAN NOT NULL DEFAULT TRUE,
  is_spicy BOOLEAN NOT NULL DEFAULT FALSE,
  prep_minutes SMALLINT NOT NULL DEFAULT 15 CHECK (prep_minutes > 0),
  is_available BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_menu_available ON menu_items(restaurant_id, category_id, is_available, sort_order);

CREATE TABLE item_options (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id BIGINT NOT NULL REFERENCES menu_items(id) ON DELETE CASCADE,
  type VARCHAR(12) NOT NULL CHECK (type IN ('SIZE','SPICE','ADDON')),
  label VARCHAR(80) NOT NULL,
  price_delta NUMERIC(10,2) NOT NULL DEFAULT 0,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (item_id, type, label)
);

CREATE TABLE table_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_id BIGINT NOT NULL REFERENCES restaurant_tables(id),
  customer_id BIGINT REFERENCES customers(id) ON DELETE SET NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','BILL_REQUESTED','PAID','CLOSED')),
  started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  ended_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX idx_open_table_session ON table_sessions(table_id) WHERE status IN ('OPEN','BILL_REQUESTED');

CREATE TABLE orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_number VARCHAR(32) NOT NULL UNIQUE,
  customer_id BIGINT NOT NULL REFERENCES customers(id),
  session_id BIGINT REFERENCES table_sessions(id),
  kot_number INTEGER NOT NULL DEFAULT 1,
  order_type VARCHAR(16) NOT NULL CHECK (order_type IN ('DINE_IN','DELIVERY')),
  status VARCHAR(24) NOT NULL DEFAULT 'NEW' CHECK (status IN ('NEW','ACCEPTED','PREPARING','READY','OUT_FOR_DELIVERY','SERVED','DELIVERED','CANCELLED')),
  address JSONB,
  subtotal NUMERIC(10,2) NOT NULL,
  tax NUMERIC(10,2) NOT NULL DEFAULT 0,
  service_charge NUMERIC(10,2) NOT NULL DEFAULT 0,
  delivery_fee NUMERIC(10,2) NOT NULL DEFAULT 0,
  total NUMERIC(10,2) NOT NULL,
  payment_status VARCHAR(16) NOT NULL DEFAULT 'UNPAID' CHECK (payment_status IN ('UNPAID','PAID','FAILED')),
  idempotency_key VARCHAR(100),
  placed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK ((order_type='DINE_IN' AND session_id IS NOT NULL) OR (order_type='DELIVERY' AND address IS NOT NULL))
);
CREATE UNIQUE INDEX idx_order_idempotency ON orders(customer_id, idempotency_key) WHERE idempotency_key IS NOT NULL;
CREATE UNIQUE INDEX idx_order_session_kot ON orders(session_id,kot_number) WHERE session_id IS NOT NULL;
CREATE INDEX idx_orders_recent ON orders(placed_at DESC);
CREATE INDEX idx_orders_status ON orders(status, placed_at DESC);

CREATE TABLE order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  menu_item_id BIGINT REFERENCES menu_items(id) ON DELETE SET NULL,
  item_name VARCHAR(120) NOT NULL,
  quantity SMALLINT NOT NULL CHECK (quantity > 0),
  unit_price NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
  line_total NUMERIC(10,2) NOT NULL CHECK (line_total >= 0),
  options JSONB NOT NULL DEFAULT '{}',
  note VARCHAR(300) NOT NULL DEFAULT '',
  station_id BIGINT REFERENCES stations(id) ON DELETE SET NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'NEW' CHECK (status IN ('NEW','PREPARING','READY','SERVED','CANCELLED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_order_items_kitchen ON order_items(station_id, status);

CREATE TABLE service_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id BIGINT NOT NULL REFERENCES table_sessions(id) ON DELETE CASCADE,
  type VARCHAR(40) NOT NULL,
  status VARCHAR(12) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','DONE')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  resolved_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX idx_active_service_request ON service_requests(session_id,type) WHERE status='OPEN';

CREATE TABLE delivery_jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id) ON DELETE CASCADE,
  staff_id BIGINT REFERENCES staff(id) ON DELETE SET NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'UNASSIGNED' CHECK (status IN ('UNASSIGNED','ASSIGNED','PICKED_UP','ON_THE_WAY','DELIVERED','FAILED')),
  estimated_minutes SMALLINT NOT NULL DEFAULT 45,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  method VARCHAR(20) NOT NULL CHECK (method IN ('DEMO','CASH','UPI','CARD')),
  amount NUMERIC(10,2) NOT NULL CHECK (amount > 0),
  status VARCHAR(16) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','CONFIRMED','FAILED')),
  is_simulated BOOLEAN NOT NULL DEFAULT TRUE,
  reference VARCHAR(80) NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE bills (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id BIGINT REFERENCES table_sessions(id),
  order_id BIGINT REFERENCES orders(id),
  subtotal NUMERIC(10,2) NOT NULL,
  tax NUMERIC(10,2) NOT NULL,
  service_charge NUMERIC(10,2) NOT NULL DEFAULT 0,
  total NUMERIC(10,2) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','PARTIALLY_PAID','PAID','VOID')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (session_id IS NOT NULL OR order_id IS NOT NULL)
);

CREATE TABLE reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL REFERENCES customers(id),
  order_id BIGINT REFERENCES orders(id) ON DELETE CASCADE,
  session_id BIGINT REFERENCES table_sessions(id) ON DELETE CASCADE,
  rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment VARCHAR(1000) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (order_id IS NOT NULL OR session_id IS NOT NULL)
);
CREATE UNIQUE INDEX idx_one_review_per_order ON reviews(order_id) WHERE order_id IS NOT NULL;

CREATE TABLE points_ledger (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  order_id BIGINT REFERENCES orders(id) ON DELETE SET NULL,
  delta INTEGER NOT NULL,
  reason VARCHAR(120) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id BIGINT REFERENCES staff(id) ON DELETE SET NULL,
  action VARCHAR(100) NOT NULL,
  entity_type VARCHAR(40) NOT NULL,
  entity_id BIGINT,
  details JSONB NOT NULL DEFAULT '{}',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
